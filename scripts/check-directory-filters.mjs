async (page) => {
  const base = new URL(page.url()).origin;
  const checks = [];
  const assert = (ok, message) => { if (!ok) throw new Error(message); checks.push(message); };
  await page.goto(base + '/servers?software=mastodon&reg=open&sort=name&dir=desc&page_size=25');
  await page.waitForFunction(() => document.querySelector('.portal-root')?.dataset.ready === 'true');
  const panel = page.locator('.directory-filter-panel');
  assert(!(await panel.getAttribute('open')), 'Advanced filters start collapsed');
  const registration = page.getByLabel('가입 방식',{exact:true});
  assert(await registration.isVisible(), 'Primary registration filter is visible while advanced filters are collapsed');
  const summary = page.locator('.directory-results-summary');
  assert(await summary.locator('.directory-result-count').isVisible() && await summary.getByRole('link',{name:'소프트웨어: Mastodon 해제',exact:true}).isVisible(), 'Result count and applied filters share one summary');
  assert(await page.getByRole('link', {name:'소프트웨어: Mastodon 해제',exact:true}).isVisible(), 'Applied software is visible and removable outside the collapsed panel');
  await page.getByRole('link', {name:'소프트웨어: Mastodon 해제',exact:true}).click();
  await page.waitForURL(url => !url.searchParams.has('software'));
  const url = new URL(page.url());
  assert(url.searchParams.get('reg')==='open' && url.searchParams.get('sort')==='name' && url.searchParams.get('dir')==='desc' && url.searchParams.get('page_size')==='25', 'Removing one filter preserves unrelated filters and sort');
  await registration.selectOption('invite_only');
  assert(await page.getByText('조건이 바뀌었어요. 검색 또는 조건 적용을 눌러 반영하세요.',{exact:true}).isVisible(), 'Unsaved primary filter changes have explicit pending feedback');
  await page.getByRole('button',{name:'검색',exact:true}).click();
  await page.waitForURL(url => url.searchParams.get('reg')==='invite_only' && url.searchParams.get('sort')==='name' && url.searchParams.get('dir')==='desc' && url.searchParams.get('page_size')==='25');
  await page.getByRole('link',{name:'가입 방식: 초대 필요 해제',exact:true}).waitFor({state:'visible'});
  assert(await page.getByRole('link',{name:'가입 방식: 초대 필요 해제',exact:true}).isVisible(), 'Collapsed primary filter applies by searching and appears in the URL/chips');

  await page.locator('.directory-filter-panel > summary').click();
  assert(await registration.isVisible(), 'Primary registration filter remains available when advanced filters expand');
  const health = page.getByLabel('응답 상태',{exact:true});
  await health.selectOption('no');
  assert(await page.getByText('조건이 바뀌었어요. 검색 또는 조건 적용을 눌러 반영하세요.',{exact:true}).isVisible(), 'Unsaved advanced filter changes have explicit pending feedback');
  await page.getByRole('button',{name:'조건 적용',exact:true}).click();
  await page.waitForURL(url => url.searchParams.get('reg')==='invite_only' && url.searchParams.get('alive')==='no');
  await page.getByRole('link',{name:'응답 상태: 최근 응답 없음 해제',exact:true}).waitFor({state:'visible'});
  assert(await summary.locator('.directory-result-count').isVisible() && await summary.getByRole('link',{name:'가입 방식: 초대 필요 해제',exact:true}).isVisible() && await summary.getByRole('link',{name:'응답 상태: 최근 응답 없음 해제',exact:true}).isVisible(), 'Updated result count and all applied filters remain grouped');
  await page.reload();await page.waitForFunction(()=>document.querySelector('.portal-root')?.dataset.ready==='true');
  assert(await registration.inputValue()==='invite_only' && await health.inputValue()==='no', 'Applied filters survive reload');
  await page.getByRole('link',{name:'모두 해제',exact:true}).click();
  await page.waitForURL(url => url.pathname==='/servers' && !url.search);
  await page.waitForFunction(()=>!document.querySelector('.active-filter-chips') && !!document.querySelector('.directory-result-count'));
  assert(await page.locator('.active-filter-chips a').count()===0, 'Reset restores the canonical unfiltered route');
  return {checks};
}
